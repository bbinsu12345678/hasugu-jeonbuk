/**
 * 본문 구조 풀 (12개 패턴)
 *
 * G5: 섹션 순서·선택을 다양하게 조합하여 본문 흐름 자체에 변형 부여.
 * 같은 텍스트라도 순서가 다르면 네이버 유사 문서 판정에서 분리됨.
 *
 * 6개 섹션 (s0~s5) 의미:
 * - 0: 원인/증상 분석
 * - 1: 우리 서비스 소개
 * - 2: 업체 선택 체크포인트
 * - 3: 실제 후기/사례
 * - 4: 예방 / 관리 팁
 * - 5: 보증·A/S·정기 관리 약속 (신규, Phase 3)
 *
 * 각 permutation 은 5-of-6 부분집합 + 순서 — 페이지당 5개 섹션 렌더.
 * 전체 풀에 index 5 가 포함된 패턴(I~L) 추가 → 같은 서비스 내 본문 다양성 ↑.
 */

export const bodyStructures: Array<number[]> = [
  [0, 1, 2, 3, 4], // A: 표준
  [3, 0, 2, 1, 4], // B: 후기 먼저
  [1, 2, 0, 3, 4], // C: 서비스 먼저
  [0, 3, 1, 2, 4], // D: 원인 → 후기 → 서비스 → 체크 → 예방
  [2, 0, 1, 3, 4], // E: 체크 → 원인 → 서비스 → 후기 → 예방
  [3, 1, 0, 2, 4], // F: 후기 → 서비스 → 원인 → 체크 → 예방
  [4, 0, 1, 3, 2], // G: 예방 → 원인 → 서비스 → 후기 → 체크
  [0, 2, 3, 1, 4], // H: 원인 → 체크 → 후기 → 서비스 → 예방
  [0, 1, 5, 3, 4], // I: 원인 → 서비스 → 보증 → 후기 → 예방
  [0, 3, 5, 1, 4], // J: 원인 → 후기 → 보증 → 서비스 → 예방
  [0, 1, 2, 5, 4], // K: 원인 → 서비스 → 체크 → 보증 → 예방
  [3, 0, 1, 5, 2], // L: 후기 → 원인 → 서비스 → 보증 → 체크
];

export function pickBodyStructure(hash: number): number[] {
  return bodyStructures[hash % bodyStructures.length];
}
